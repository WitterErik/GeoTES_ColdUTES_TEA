"""Formatting and printing of annual CSP–GeoTES model results."""

import numpy as np


def print_report(results):
    """Print the detailed comparison report from calculated model results."""
    plant = results.plant
    csp, cycle, geotes, econ = plant.csp, plant.power_cycle, plant.geotes, plant.economics
    year_start, year_end = results.year_start, results.year_end
    power_final_year = geotes.power[year_start:year_end]
    positive_wout = cycle.Wout[year_start:year_end]
    positive_wout = positive_wout[positive_wout > 0]

    print("\nPOWER OUTPUTS\n")
    print(f"Maximum solar power generated             = {np.max(csp.power):6.2f} MW-th")
    print(f"Power cycle power output                  = {cycle.Wout0:6.2f} MW-e")
    print(f"Average power cycle output                = {np.mean(positive_wout) if positive_wout.size else 0.0:6.2f} MW-e")
    print(f"Max. thermal power into subsurface        = {np.max(power_final_year):6.2f} MW-th")
    print(f"Max. thermal power out of subsurface      = {-np.min(power_final_year):6.2f} MW-th")
    print(f"Charge production pump power              = {results.charge_prod_duty[0] / 1e3:6.2f} MW-e")
    print(f"Charge injection pump power               = {results.charge_inj_duty[0] / 1e3:6.2f} MW-e")
    print(f"Discharge production pump power           = {results.discharge_prod_duty[0] / 1e3:6.2f} MW-e")
    print(f"Discharge injection pump power            = {results.discharge_inj_duty[0] / 1e3:6.2f} MW-e")

    print("\nANNUAL ENERGY OUTPUTS\n")
    print(f"Available solar heat                      = {csp.available_solar_heat:6.2f} GWh-th")
    print(f"Solar heat generated                      = {csp.solar_thermal_generated:6.2f} GWh-th")
    print(f"Dumped solar heat                         = {csp.total_dumped:6.2f} GWh-th\n")
    print(f"Heat delivered to low-temp. cycle         = {cycle.Qin_tot:6.2f} GWh-th")
    print(f"Electricity generated by low-temp. cycle  = {cycle.Wout_tot:6.2f} GWh-e")
    print(f"Discharge condenser fan parasitic         = {results.discharge_air_fan:6.2f} GWh-e\n")
    print(f"Heat delivered to thermal load            = {econ.Qout:6.2f} GWh-th")
    load_capacity_factor = 100 * econ.Qout / (results.qload * 8760) if results.qload else 0.0
    print(f"Thermal load capacity factor              = {load_capacity_factor:6.2f} %\n")
    print(f"Heat delivered to geoTES                  = {geotes.energy_in_tot:6.2f} GWh-th")
    print(f"Heat extracted from geoTES                = {geotes.energy_out_tot:6.2f} GWh-th")
    print(f"Max. energy stored in geoTES              = {geotes.energy_capacity:6.2f} GWh-th")
    print(f"Max. hours of power delivery              = {results.geotes_max_hours:6.2f} h")
    print(f"Approx. electricity from max. hours       = {results.geotes_max_elec:6.2f} GWh-e\n")
    print(f"Net annual change in geoTES capacity      = {geotes.net_energy:6.2f} GWh-th")
    print(f"Equivalent hours of power delivery        = {results.geotes_capacity_hours:6.2f} h")
    print(f"Approx. electricity from space capacity   = {results.geotes_capacity_elec:6.2f} GWh-e\n")
    print(f"Charge production pump consumption        = {results.charging_hours * results.charge_prod_duty[0] / 1e6:6.2f} GWh-e")
    print(f"Charge injection pump consumption         = {results.charging_hours * results.charge_inj_duty[0] / 1e6:6.2f} GWh-e")
    print(f"Discharge production pump consumption     = {results.discharging_hours * results.discharge_prod_duty[0] / 1e6:6.2f} GWh-e")
    print(f"Discharge injection pump consumption      = {results.discharging_hours * results.discharge_inj_duty[0] / 1e6:6.2f} GWh-e\n")
    print(f"Net electricity generated                 = {results.net_electricity:6.2f} GWh-e")
    print(f"Capacity factor                           = {results.capacity_factor:6.2f} %\n")
    print(f"Number of charging production wells       = {geotes.charge_prod_Nwell:6.2f}")
    print(f"Number of charging injection wells        = {geotes.charge_inj_Nwell:6.2f}")
    print(f"Number of discharging production wells    = {geotes.discharge_prod_Nwell:6.2f}")
    print(f"Number of discharging injection wells     = {geotes.discharge_inj_Nwell:6.2f}\n")

    print("\nSUBSURFACE COST RESULTS\n")
    print(f"Total Exploration Cost          = {results.exploration_cost / 1e6:6.2f} M$")
    print(f"Permitting cost                 = {results.permitting_cost / 1e6:6.2f} M$\n")
    print(f"Total Charge Drilling Cost      = {(results.charge_drill_prod + results.charge_drill_inj) / 1e6:6.2f} M$")
    print(f"Charge production pump cost     = {results.charge_prod_duty[1] / 1e6:6.2f} M$")
    print(f"Charge injection pump cost      = {results.charge_inj_duty[1] / 1e6:6.2f} M$")
    print(f"Charge flow line cost           = {results.charge_flowline / 1e6:6.2f} M$\n")
    print(f"Total Discharge Drilling Cost   = {(results.discharge_drill_prod + results.discharge_drill_inj) / 1e6:6.2f} M$")
    print(f"Discharge production pump cost  = {results.discharge_prod_duty[1] / 1e6:6.2f} M$")
    print(f"Discharge injection pump cost   = {results.discharge_inj_duty[1] / 1e6:6.2f} M$")
    print(f"Discharge flow line cost        = {results.discharge_flowline / 1e6:6.2f} M$\n")
    print(f"Subsurface Capital Cost         = {results.subsurface_capital / 1e6:6.2f} M$")
    print(f"Subsurface O&M Cost             = {results.subsurface_om / 1e6:6.2f} M$")
    storage_capital = results.subsurface_capital / (geotes.energy_capacity * 1e6) if geotes.energy_capacity else 0.0
    print(f"Capital cost of storage         = {storage_capital:6.2f} $/kWh-th\n")

    print("SURFACE COST RESULTS\n")
    print(f"Solar field cost                = {csp.total_cost / 1e6:6.2f} M$")
    print(f"Low-temp. power cycle cost      = {cycle.total_cost / 1e6:6.2f} M$\n")
    print(f"Surface capital cost            = {econ.surface_capital_cost / 1e6:6.2f} M$")
    print(f"Surface O&M cost                = {econ.OnM_surface / 1e6:6.2f} M$\n")

    print("TOTAL COST RESULTS\n")
    print(f"Total capital cost              = {econ.total_capital_cost / 1e6:6.2f} M$")
    print(f"LCOE                            = {econ.LCOE:6.3f} $/kWh-e")
    print(f"LCOH                            = {econ.LCOH:6.3f} $/kWh-th")
    print(f"GeoTES contribution to LCOE     = {results.geotes_lcoe:6.3f} $/kWh-e\n")
    print(f"Cost results including an investment tax credit of {100 * econ.ITC:4.2f}%")
    print(f"Total capital cost (ITC)        = {econ.total_capital_cost_ITC / 1e6:6.2f} M$")
    print(f"LCOE (ITC)                      = {econ.LCOE_ITC:6.3f} $/kWh-e")
    print(f"LCOH (ITC)                      = {econ.LCOH_ITC:6.3f} $/kWh-th")
    print(f"GeoTES contribution to LCOE (ITC) = {results.geotes_lcoe_itc:6.3f} $/kWh-e\n")
